# String Methods: Searching and Replacing
# count(): Substring Frequency
# find(): Locate First Occurrence
# index(): Locate (with Error)
# replace(): Substitute Substrings


text="anirudh khurana"
print(text.count("a"))
print(text.count("an"))
print(text.find("a"))
print(text.find("khurana"))
print(text.index("a"))
print(text.replace("a","z"))
print(text.replace("a","n"))