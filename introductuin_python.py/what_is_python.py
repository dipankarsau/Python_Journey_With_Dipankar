# What is Python?

# Python is a high-level, general-purpose programming language. It was
# created by Guido van Rossum and first released in 1991. The goal behind
# Python was simple - write code that reads almost like plain English, so
# developers can focus on solving problems rather than fighting with syntax.

# . Easy to read and write -> minimal boilerplate, clean syntax
# . Interpreted -> code runs line by line, no compilation needed
# . Dynamically typed -> you don't declare variable types manually
# . Hugely versatile -> web, data, Al, automation, all of it